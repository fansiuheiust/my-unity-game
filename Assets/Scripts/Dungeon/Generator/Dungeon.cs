namespace Dungeon.Generator {
    /// <summary>
    /// The dungeon
    /// </summary>
    public class Dungeon {
        internal List<Room> rooms = new();
        /// <summary>
        /// jagged list of rooms grouped by abs layer (|y| - y = -1 => abs layer = |-1| = 1)
        /// </summary>
        internal List<List<Room>> layeredRooms = new();

        // variables controlling the room's generation
        /// <summary>
        /// List of rooms the generator can choose from
        /// </summary>
        public (string, RoomType, Vector2Int[])[] Options { get; private set; }
        /// <summary>
        /// The length of the path from start room to final room, *excluding* the start and final room
        /// </summary>
        public uint MainPathLength { get; private set; }
        /// <summary>
        /// Number of rooms to include for each room type, do not include start, ladder and final room
        /// </summary>
        public Dictionary<RoomType, uint> NumRooms = new();
        /// <summary>
        /// number of rooms left to spawn for each room type
        /// </summary>
        Dictionary<RoomType, uint> spawnRequirement;
        /// <summary>
        /// The expected length of a side path *when it is generated* (i.e. if another side path links from a side path, the original one's length is expected to be doubled)
        /// </summary>
        public uint ExpectedSidePathLength { get; private set; }
        /// <summary>
        /// Generation: given a side room is generated. It has a probability p of being extended, and so is its extension. <br />
        /// Given we want to generate s side paths on average, find p in terms of s.<br />
        /// E(X) + 1 = s
        /// 1/(1-p) - 1 + 1 = s
        /// => 1-p = 1/s
        /// => p = 1-1/s
        /// </summary>
        float SideRoomChainProbability => 1 - 1f / ExpectedSidePathLength;


        internal List<Connection> Connections { get; private set; } = new();

        /// <summary>
        /// Generates the dungeon
        /// </summary>
        /// <param name="options"><seealso cref="Options"/></param>
        /// <param name="mainPathLength"><seealso cref="MainPathLength"/></param>
        /// <param name="numRooms"><seealso cref="NumRooms"/></param>
        /// <param name="isLayered">Whether the generated dungeon should consist of multiple layers (i.e. different y level)</param>
        /// <param name="expectedSidePathLength"><seealso cref="ExpectedSidePathLength"/></param>
        /// <exception cref="System.Exception"></exception>
        public Dungeon((string, RoomType, Vector2Int[])[] options, uint mainPathLength, Dictionary<RoomType, uint> numRooms, bool isLayered = true, uint expectedSidePathLength = 2) {
            if (!options.All(x =>numRooms.ContainsKey(x.Item2)))
                throw new System.Exception("All roomtypes in options must appear in numRooms once");
            if (mainPathLength > numRooms.Sum(x=>x.Value))
                throw new System.Exception("The main path's length cannot be larger than the number of rooms");
            if (mainPathLength != numRooms.Sum(x=>x.Value) && expectedSidePathLength == 0)
                throw new System.Exception("If the main paths's length is smaller than the number of rooms, expectedSidePathLength must be non-zero");
            Options = options;
            MainPathLength = mainPathLength;
            NumRooms = numRooms;
            spawnRequirement = numRooms.ToDictionary(x=>x.Key, x=>x.Value);
            ExpectedSidePathLength = expectedSidePathLength;
            Generate(isLayered);
        }

        /// <summary>
        /// All the rooms generated by the generator, note that <c>blocks</c> include center
        /// </summary>
        public List<(RoomType type, string shape, Vector3Int[] blocks, Vector3Int center, uint rotation)> GeneratedRooms => rooms.Select(r => (r.Type, r.ShapeName, r.Blocks.Select(b => b.coordinate).ToArray(), r.Center, r.NormalizedRotation*90)).ToList();
        /// <summary>
        /// All connections, <c>a</c> corresponds to the index of room a in <c>GeneratedRooms</c>
        /// </summary>
        public List<(int a, int b, Vector3Int posA, Vector3Int posB)> GeneratedConnections => Connections.Select(c=>(rooms.IndexOf(c.a), rooms.IndexOf(c.b), c.posA, c.posB)).ToList();


        /// <summary>
        /// The smallest XYZ coordinates respectively in the entire dungeon
        /// </summary>
        public Vector3Int MinCorner => new(rooms.Min(r => r.MinCorner.x), rooms.Min(r => r.MinCorner.y), rooms.Min(r => r.MinCorner.z));
        /// <summary>
        /// The largest XYZ coordinates respectively in the entire dungeon
        /// </summary>
        public Vector3Int MaxCorner => new(rooms.Max(r => r.MaxCorner.x), rooms.Max(r => r.MinCorner.y), rooms.Max(r => r.MaxCorner.z));



        /// <summary>
        /// The big thing that generates the dungeon
        /// </summary>
        /// <param name="isLayered">Whether the dungeon should expand vertically (y)</param>
        void Generate(in bool isLayered) {
            GenerateMainPath(in isLayered);
            GenerateSideRooms();
        }

        /// <summary>
        /// Main path generator
        /// </summary>
        /// <param name="isLayered">whether</param>
        void GenerateMainPath(in bool isLayered) {
        Redo:
            // the starting room
            rooms.Add(Room.Start);
            layeredRooms.Add(new());
            layeredRooms[0].Add(rooms[0]);
            Room prev = rooms[0];
            int consecutiveFailCount = 0;
            // generate main path
            for (int i = 0; i < MainPathLength+1; i++) { // +1 as final room will also be generated here
                bool createdRoom = false;
                // insert callback hell meme but for loop

                // loop through rom where rom = a potential room
                foreach ((string, RoomType, Vector2Int[]) rom in RoomSpawnList) {
                    Room toSpawn = (i == MainPathLength)? 
                        Room.Final: 
                        new(0, 0, rom.Item1, rom.Item2,
                            rom.Item3.Select(x=>new Block(x.x, x.y)).ToArray());

                    // loop through blk where blk = each block of the previous room
                    IEnumerable<Block> shuffledPrevBlocks = prev.Blocks.OrderBy(b => Random.value);
                    if (prev.Type == RoomType.Ladder) shuffledPrevBlocks = shuffledPrevBlocks.Where(b => b.coordinate != prev.Center); // skip the upper block if ladder
                    foreach (Block blk in shuffledPrevBlocks) {
                        // loop through edg where edg = all valid edges of blk
                        IEnumerable<Vector3Int> shuffledEdges = EdgeOf(blk).OrderBy(x => Random.value);
                        foreach (Vector3Int edg in shuffledEdges) {
                            createdRoom = TrySpawnRoom(toSpawn, prev, blk, edg);
                            if (createdRoom) {
                                prev = rooms[^1];
                                break;
                            }
                        }
                        if (createdRoom) break;
                    }
                    if (createdRoom) break;
                }

                if (!createdRoom) {
                    i--;
                    consecutiveFailCount++;
                    if (consecutiveFailCount >= 10) {

                        if (isLayered)
                        {

                            if (spawnRequirement.ContainsKey(prev.Type)) spawnRequirement[prev.Type]++;

                            layeredRooms.Add(new());
                            Room r = Room.Ladder;
                            r.Center = Connections[^1].posB;
                            Connections[^1] = new Connection(Connections[^1].a, r, Connections[^1].posA, Connections[^1].posB);
                            rooms.Remove(prev);
                            layeredRooms[-prev.Center.y].Remove(prev);
                            rooms.Add(r);
                            // a ladder room will appear in both both y = -i-1 and y = -i
                            layeredRooms[^1].Add(r);
                            layeredRooms[^2].Add(r);
                            prev = r;
                            i--; // this room should not be counted towards no. of rooms
                        }

                        else {
                            spawnRequirement = NumRooms.ToDictionary(x => x.Key, x => x.Value);
                            rooms.Clear();
                            layeredRooms.Clear();
                            Connections.Clear();
                            goto Redo;
                        }
                    }
                } else consecutiveFailCount = 0;
            }
        }

        void GenerateSideRooms() {
            // for each iteration, always try to extend the first element of it if it is not empty
            Room extendCandidate = null;

            int[] edgeCounts = new int[layeredRooms.Count];
            for (int i = 0; i < layeredRooms.Count; i++)
                edgeCounts[i] = EdgeOf(i).Count();

            while (spawnRequirement.Sum(x => x.Value) > 0) {
                // choose a layer first such that the dungeon generator only needs to consider rooms in the same layer instead of the entire room
                // the probability of a layer to be chosen = no. of edges for the layer/total no. of edges
                int chosenLayer = 0;
                if (extendCandidate is null) {
                    float accumulator = edgeCounts[0];
                    float rng = Random.value;
                    for (int i = 1; i < edgeCounts.Length; i++) {
                        if (accumulator / edgeCounts.Sum() < rng && rng <= (accumulator + edgeCounts[i]) / edgeCounts.Sum()) {
                            chosenLayer = i;
                            break;
                        }
                        accumulator += edgeCounts[i];
                    }
                } else {
                    chosenLayer = -extendCandidate.Center.y;
                }
                // choose an edge
                IEnumerable<Vector3Int> edgeCandidates = extendCandidate is not null ?
                    EdgeOf(extendCandidate):
                    EdgeOf(chosenLayer);
                if (edgeCandidates.Count() == 0) {
                    extendCandidate = null;
                    continue;
                }
                Vector3Int chosenEdge = edgeCandidates.OrderBy(_ => Random.value).FirstOrDefault();
                // associate the edge with the correct random block
                Room associatedRoom = extendCandidate is not null?
                    extendCandidate:
                    layeredRooms[-chosenEdge.y]
                        .Where(r=>r.Type != RoomType.Final && r.Type != RoomType.Start && r.Blocks.Any(b=>b.HammingDistance(chosenEdge) == 1))
                        .OrderBy(_ => Random.value)
                        .FirstOrDefault();
                Block associatedBlock = associatedRoom.Blocks
                    .Where(b => b.HammingDistance(chosenEdge) == 1)
                    .OrderBy(_ => Random.value)
                    .FirstOrDefault();
                // try to spawn a room
                bool spawnedRoom = false;

                foreach (Room toSpawn in RoomCandidates) {
                    spawnedRoom = TrySpawnRoom(toSpawn, associatedRoom, associatedBlock, chosenEdge);
                    if (spawnedRoom) {
                        // also needs to uppdate no. of edges for the corresponding room
                        edgeCounts[chosenLayer]++;
                        extendCandidate = Random.value < SideRoomChainProbability? toSpawn: null;
                        break;
                    }
                }
                if (!spawnedRoom) {
                    extendCandidate = null;
                }
            }
        }


        /// <summary>
        /// <para>Tries to spawn a room given a predetermined edge and block to spawn it at.</para>
        /// The algorithm will try to fit the room into the dungeon by trying: <br />
        /// -all rotation <br />
        /// -all positions of each rotation such that a block of the room is both in <c>e</c> and is next to <c>b</c>
        /// </summary>
        /// <param name="r">The candidate room</param>
        /// <param name="connector">The room that should be connected to the new room</param>
        /// <param name="b">Block the new room should be next to</param>
        /// <param name="e"></param>
        /// <returns>Whether the room is successfully spawned</returns>
        bool TrySpawnRoom(Room r, in Room connector, in Block b, in Vector3Int e) {
            r.NormalizedRotation = 0;
            foreach (uint rotation in new uint[]{ 0, 1, 2, 3}.OrderBy(x=>Random.value)) {
                r.Center = Vector3Int.zero;
                r.NormalizedRotation = rotation;
                Vector3Int dist = b.coordinate-e;
                // for some reason, this thing returned an enumerable of references to coordinates of r's blocks wtf
                IEnumerable<Vector3Int> compatibleBlockPositions = r.Blocks.Select(b => b.coordinate).Where(c => !r.Contains(c + dist)).ToList();
                foreach(Vector3Int pos in compatibleBlockPositions) {
                    // center + pos = edge => 
                    r.Center = e - pos;
                    if (layeredRooms[-e.y].All(r2=>!r2.Collides(r))) {
                        rooms.Add(r);
                        layeredRooms[-e.y].Add(r);
                        Connections.Add(new(connector, r, b.coordinate, e));
                        if (spawnRequirement.ContainsKey(r.Type)) spawnRequirement[r.Type]--;
                        return true;
                    }
                }
                
            }

            return false;
        }

        IEnumerable<(string, RoomType, Vector2Int[])> RoomSpawnList => Options.Where(x => spawnRequirement[x.Item2] > 0)
            .OrderBy(x=>Random.value);

        Room[] RoomCandidates => RoomSpawnList.Select(x => new Room(x)).ToArray();

        /// <summary>
        /// Gets an ordered set of valid edges of a specified block
        /// </summary>
        /// <param name="b">self-documenting</param>
        IEnumerable<Vector3Int> EdgeOf(in Block b) => b.Edges.Where(e => !layeredRooms[-e.y].Any(r => r.Contains(e)));

        /// <summary>
        /// Gets an ordered set of valid edges of a specified room
        /// </summary>
        /// <param name="r">self-documenting</param>
        IEnumerable<Vector3Int> EdgeOf(in Room r) => r.UnfilteredEdges
            .Distinct()
            .Where(e => layeredRooms[-e.y].All(r2=>!r2.Contains(e)));

        /// <summary>
        /// Gets an ordered set of valid edges in the specified layer
        /// </summary>
        /// <param name="absLayer">the layer, note that it should be positive</param>
        IEnumerable<Vector3Int> EdgeOf(int absLayer) => layeredRooms[absLayer]
            .Where(r => r.Type != RoomType.Start && r.Type != RoomType.Final)
            .SelectMany(r => r.UnfilteredEdges)
            .Distinct()
            .Where(c => layeredRooms[absLayer].All(r => !r.Contains(c)));



        public void Print() {
            string toPrint = "";
            Debug.Log(toPrint);
            toPrint = "";
            foreach (Room r in rooms) {
                toPrint += $"{r.ShapeName}: {r.Center}, {r.NormalizedRotation*90}\n";
            }
            Debug.Log(toPrint);
        }

        public List<GameObject> Visualize() {
            List<GameObject> objects = new();
            int minY = MinCorner.y;
            foreach (Room r in rooms) {
                GameObject go = MonoBehaviour.Instantiate(Resources.Load<GameObject>($"RoomVisualizer/{r.Type}/{r.ShapeName}"));
                go.transform.position = r.Center - new Vector3(0, minY-1f, 0);
                go.transform.localEulerAngles = new(0, r.RotationInGame,0);
                objects.Add(go);
            }
            string connSource = "Main";
            foreach (Connection c in Connections) {
                GameObject go = MonoBehaviour.Instantiate(Resources.Load<GameObject>($"RoomVisualizer/Connection/{connSource}"));
                go.transform.position = new((c.posA.x+c.posB.x)/2f,0.1f + System.Math.Min(c.posA.y, c.posB.y) - minY+1f,(c.posA.z+c.posB.z)/2f);
                objects.Add(go);
                if (c.b.Type == RoomType.Final) connSource = "Side";
            }
            return objects;
        }
    }

    public static class Driver {

        static List<GameObject> SpawnedObjects;
        public static void Main() {
            if (SpawnedObjects != null) {
                foreach (GameObject obj in SpawnedObjects) { MonoBehaviour.Destroy(obj);}
            }


            (string, RoomType, Vector2Int[])[] options = {
                ("1x1", RoomType.Mob, new Vector2Int[]{}), // 1x1
                ("1x2", RoomType.Mob, new Vector2Int[]{Vector2Int.right}), // 1x2
                ("L", RoomType.Mob, new Vector2Int[]{Vector2Int.up, Vector2Int.right}), // L
                ("1x3", RoomType.Mob, new Vector2Int[]{Vector2Int.left, Vector2Int.right}), // 1x3
                ("2x2", RoomType.Mob, new Vector2Int[]{Vector2Int.right, Vector2Int.up, Vector2Int.one}), // 2x2
                ("Plus", RoomType.Mob, new Vector2Int[] { Vector2Int.left, Vector2Int.right, Vector2Int.up, Vector2Int.down }) // +
            };
            Dungeon d = new Dungeon(options, 1024, new(){ { RoomType.Mob, 1666 }}, isLayered: true, expectedSidePathLength: 4);
            d.Print();
            SpawnedObjects = d.Visualize();
        }
    }
