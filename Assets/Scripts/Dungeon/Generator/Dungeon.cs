using System.Collections.Generic;
using System.Linq;
using UnityEngine;

namespace Dungeon.Generator {
    /// <summary>
    /// The dungeon
    /// </summary>
    public class Dungeon {
        internal Dictionary<Vector2Int, Room> rooms = new();

        // variables controlling the room's generation
        /// <summary>
        /// List of rooms the generator can choose from
        /// </summary>
        public (RoomType, Vector2Int[])[] Options { get; private set; }
        /// <summary>
        /// The length of the path from start room to end room
        /// </summary>
        public uint MainPathLength { get; private set; }
        /// <summary>
        /// <para>The minimum number of rooms for each roomtype.</para>
        /// If a roomtype is not hashed to anything, it is considered as unrestricted (i.e. no minimum).<br />
        /// If the dictionary is empty, it is considered as no minimum for all rooms
        /// </summary>
        public Dictionary<RoomType, uint> MinNumRooms { get; private set; }
        /// <summary>
        /// <para>The maximum number of rooms for each roomtype.</para>
        /// If a roomtype is not hashed to anything, it is considered as unlimited (i.e. no maximum).<br />
        /// If the dictionary is empty, it is considered as no minimum for all rooms
        /// </summary>
        public Dictionary<RoomType, uint> MaxNumRooms { get; private set; }
        /// <summary>
        /// The maximum number of rooms in the dungeon
        /// </summary>
        public uint MaxTotalRooms { get; private set; }

        internal Dictionary<(Room, Room), Connection> Connections { get; private set; } = new();

        /// <summary>
        /// Generates the dungeon
        /// </summary>
        public Dungeon((RoomType, Vector2Int[])[] options, uint mainPathLength, Dictionary<RoomType, uint> minNumRooms, Dictionary<RoomType, uint> maxNumRooms, uint maxTotalRooms) {
            Options = options;
            MainPathLength = mainPathLength;
            MinNumRooms = minNumRooms;
            MaxNumRooms = maxNumRooms;
            MaxTotalRooms = maxTotalRooms;
            Generate();
        }

        /// <summary>
        /// All the rooms generated by the generator
        /// </summary>
        public IEnumerable<(RoomType, Vector2Int[])> GeneratedRooms => rooms.Select(r => (r.Value.Type, r.Value.Blocks.Select(b => b.coordinate).ToArray()));

        /// <summary>
        /// The smallest XY coordinates in the entire dungeon
        /// </summary>
        public Vector2Int Min => new(rooms.Min(r => r.Value.Min.x), rooms.Min(r => r.Value.Min.y));
        /// <summary>
        /// The largest XY coordinates in the entire dungeon
        /// </summary>
        public Vector2Int Max => new(rooms.Max(r => r.Value.Max.x), rooms.Max(r => r.Value.Max.y));



        /// <summary>
        /// The big thing that generates the dungeon
        /// </summary>
        void Generate() {
            // the starting room
            rooms.Add(new(0, 0), new(0, 0, RoomType.Start, new Block(0,0)));

        }


        IEnumerable<Vector2Int> Edges => rooms.Select(r => r.Value.UnfilteredEdges)
                                            .SelectMany(list => list)
                                            .Distinct()
                                            .Where(c => !rooms.Any(r => r.Value.Contains(c)));
        IEnumerable<Vector2Int> RandomizedEdges => Edges.OrderBy(_ => Random.value);
    }

    public static class Driver {
        public static void Main() {
            new Room(new(5, 4), RoomType.Mob, new Block(0, 0), new Block(0, 1)).Edges.ToList().ForEach(x => Debug.Log(x));
        }
    }
}