namespace Dungeon.Generator {
    /// <summary>
    /// The dungeon
    /// </summary>
    public class Dungeon {
        internal List<Room> rooms = new();
        /// <summary>
        /// jagged list of rooms grouped by abs layer (|y| - y = -1 => abs layer = |-1| = 1)
        /// </summary>
        internal List<List<Room>> layeredRooms = new();

        // variables controlling the room's generation
        /// <summary>
        /// List of rooms the generator can choose from
        /// </summary>
        public (string, RoomType, Vector2Int[])[] Options { get; private set; }
        /// <summary>
        /// The length of the path from start room to final room, including the start and final room
        /// </summary>
        public uint MainPathLength { get; private set; }
        /// <summary>
        /// Number of rooms to include for each room type, do not include start and final room
        /// </summary>
        public Dictionary<RoomType, uint> NumRooms = new();
        /// <summary>
        /// number of rooms left to spawn for each room type
        /// </summary>
        Dictionary<RoomType, uint> spawnRequirement;

        internal List<Connection> Connections { get; private set; } = new();

        /// <summary>
        /// Generates the dungeon
        /// </summary>
        public Dungeon((string, RoomType, Vector2Int[])[] options, uint mainPathLength, Dictionary<RoomType, uint> numRooms, bool isLayered = true) {
            if (!options.All(x =>numRooms.ContainsKey(x.Item2)))
                throw new System.Exception("all roomtypes in options must appear in numRooms once");
            Options = options;
            MainPathLength = mainPathLength;
            NumRooms = numRooms;
            spawnRequirement = numRooms.ToDictionary(x=>x.Key, x=>x.Value);
            Generate(isLayered);
        }

        /// <summary>
        /// All the rooms generated by the generator
        /// </summary>
        public IEnumerable<(RoomType, Vector3Int[])> GeneratedRooms => rooms.Select(r => (r.Type, r.Blocks.Select(b => b.coordinate).ToArray()));

        /// <summary>
        /// The smallest XYZ coordinates respectively in the entire dungeon
        /// </summary>
        public Vector3Int MinCorner => new(rooms.Min(r => r.MinCorner.x), rooms.Min(r => r.MinCorner.y), rooms.Min(r => r.MinCorner.z));
        /// <summary>
        /// The largest XYZ coordinates respectively in the entire dungeon
        /// </summary>
        public Vector3Int MaxCorner => new(rooms.Max(r => r.MaxCorner.x), rooms.Max(r => r.MinCorner.y), rooms.Max(r => r.MaxCorner.z));



        /// <summary>
        /// The big thing that generates the dungeon
        /// </summary>
        void Generate(in bool isLayered) {
        Redo:
            // the starting room
            rooms.Add(new(0, 0, "start", RoomType.Start, new Block(0, 0)));
            layeredRooms.Add(new());
            layeredRooms[0].Add(rooms[0]);
            Room prev = rooms[0];
            int consecutiveFailCount = 0;
            // generate main path
            for (int i = 0; i < MainPathLength-1; i++) { // -1 as startRoom counts as a room
                bool createdRoom = false;
                // insert callback hell meme but for loop

                // loop through rom where rom = a potential room
                foreach ((string, RoomType, Vector2Int[]) rom in RoomSpawnList) {
                    Room toSpawn = (i == MainPathLength-2)? new(0, 0, "final", RoomType.Final, new Block(0, 0)): new(0, 0, rom.Item1, rom.Item2,
                        rom.Item3.Select(x=>new Block(x.x, x.y)).ToArray());

                    // loop through blk where blk = each block of the previous room
                    IEnumerable<Block> shuffledPrevBlocks = prev.Blocks.OrderBy(b => Random.value);
                    if (prev.Type == RoomType.Ladder) shuffledPrevBlocks = shuffledPrevBlocks.Where(b => b.coordinate != prev.Center); // skip the upper block if ladder
                    foreach (Block blk in shuffledPrevBlocks) {
                        // loop through edg where edg = all valid edges of blk
                        IEnumerable<Vector3Int> shuffledEdges = EdgeOf(blk, layeredRooms.Count-1).OrderBy(x => Random.value);
                        foreach (Vector3Int edg in shuffledEdges) {

                            // int maxRoomSize = Options.Max(o=>o.Item3.Length);

                            // if (!HasEnoughSpace(edg, maxRoomSize*(int)(MainPathLength-1-i))) continue;

                            Vector3Int dist = edg - blk.coordinate;

                            // loop through rot where rot = all rotations for the room
                            IEnumerable<uint> rotations = new uint[] { 0, 1, 2, 3 }.OrderBy(x => Random.value);
                            foreach (uint rot in rotations) {
                                // blocks that can join the chosen block from prev
                                toSpawn.NormalizedRotation = rot;

                                // loop through com where com = all block coordinates of the rotated chosen room that can be connected to blk
                                IEnumerable<Vector3Int> compatibleBlockCoords = toSpawn.Blocks.Select(b => b.coordinate).Where(c => !toSpawn.Contains(c - dist)).OrderBy(c => Random.value);
                                foreach (Vector3Int com in compatibleBlockCoords) {
                                    // set the room's center s.t. com == edg
                                    // center + com = edg
                                    // => center = edg - com
                                    toSpawn.Center = edg - com;

                                    if (!layeredRooms[layeredRooms.Count - 1].Any(r => r.Collides(toSpawn))) {
                                        // finally, spawn the room
                                        rooms.Add(toSpawn);
                                        layeredRooms[layeredRooms.Count - 1].Add(toSpawn);
                                        Connections.Add(new(prev, toSpawn, blk.coordinate, edg)); // since edg will be where toSpawn's connector is at
                                        if (spawnRequirement.ContainsKey(toSpawn.Type)) spawnRequirement[toSpawn.Type]--;
                                        createdRoom = true;
                                        prev = toSpawn;
                                        break;
                                    }
                                }
                                if (createdRoom) break;
                                toSpawn.Center = Vector3Int.zero;
                            }
                            if (createdRoom) break;
                            toSpawn.NormalizedRotation = 0;
                        }
                        if (createdRoom) break;
                    }
                    if (createdRoom) break;
                }

                if (!createdRoom) {
                    i--;
                    consecutiveFailCount++;
                    if (consecutiveFailCount >= 10) {

                        if (isLayered)
                        {

                            if (spawnRequirement.ContainsKey(prev.Type)) spawnRequirement[prev.Type]++;

                            layeredRooms.Add(new());
                            int index = Connections.Count - 1;
                            Room r = new(Connections[index].posB, "ladder", RoomType.Ladder, new Block(new Vector3Int(0, -1, 0)));
                            Connections[index] = new Connection(Connections[index].a, r, Connections[index].posA, Connections[index].posB);
                            rooms.Remove(prev);
                            rooms.Add(r);
                            // a ladder room will appear in both both y = -i-1 and y = -i
                            layeredRooms[layeredRooms.Count - 1].Add(r);
                            layeredRooms[layeredRooms.Count - 2].Add(r);
                            prev = r;
                            i--; // this room should not be counted towards no. of rooms
                        }

                        else {
                            spawnRequirement = NumRooms.ToDictionary(x => x.Key, x => x.Value);
                            rooms.Clear();
                            Connections.Clear();
                            goto Redo;
                        }
                    }
                } else consecutiveFailCount = 0;
            }
            Debug.Log("Number of non-ladders: " + (rooms.Count(r=>r.Type != RoomType.Ladder)));
        }


        IEnumerable<(string, RoomType, Vector2Int[])> RoomSpawnList => Options.Where(x => spawnRequirement[x.Item2] > 0)
            .OrderBy(x=>Random.value);

        IEnumerable<Vector3Int> EdgeOf(in Block b) => b.Edges.Where(e => !rooms.Any(r => r.Contains(e)));
        IEnumerable<Vector3Int> EdgeOf(in Block b, int absLayer) => b.Edges.Where(e => !layeredRooms[absLayer].Any(r => r.Contains(e)));


        IEnumerable<Vector3Int> Edges => rooms
                                        .Where(r=>r.Type != RoomType.Start && r.Type != RoomType.Final)
                                        .Select(r => r.UnfilteredEdges)
                                        .SelectMany(list => list)
                                        .Distinct()
                                        .Where(c => !rooms.Any(r => r.Contains(c)));




        public void Print() {
            string toPrint = "";
            Debug.Log(toPrint);
            toPrint = "";
            foreach (Room r in rooms) {
                toPrint += $"{r.Name}: {r.Center}, {r.NormalizedRotation*90}\n";
            }
            Debug.Log(toPrint);
        }

        public List<GameObject> Visualize() {
            List<GameObject> objects = new();
            int minY = MinCorner.y;
            foreach (Room r in rooms) {
                GameObject go = MonoBehaviour.Instantiate(Resources.Load<GameObject>($"RoomVisualizer/{r.Name}"));
                go.transform.position = r.Center - new Vector3(0, minY, 0);
                go.transform.localEulerAngles = new(0, r.RotationInGame,0);
                objects.Add(go);
            }
            foreach (Connection c in Connections) {
                GameObject go = MonoBehaviour.Instantiate(Resources.Load<GameObject>("RoomVisualizer/connection"));
                go.transform.position = new((c.posA.x+c.posB.x)/2f,0.1f + System.Math.Min(c.posA.y, c.posB.y) - minY,(c.posA.z+c.posB.z)/2f);
                objects.Add(go);
            }
            return objects;
        }
    }

    public static class Driver {

        static List<GameObject> SpawnedObjects;
        public static void Main() {
            if (SpawnedObjects != null) {
                foreach (GameObject obj in SpawnedObjects) { MonoBehaviour.Destroy(obj);}
            }


            (string, RoomType, Vector2Int[])[] options = {
                ("1x1mob", RoomType.Mob, new Vector2Int[]{}), // 1x1
                ("1x2mob", RoomType.Mob, new Vector2Int[]{Vector2Int.right}), // 1x2
                ("Lmob", RoomType.Mob, new Vector2Int[]{Vector2Int.up, Vector2Int.right}), // L
                ("1x3mob", RoomType.Mob, new Vector2Int[]{Vector2Int.left, Vector2Int.right}), // 1x3
                ("2x2mob", RoomType.Mob, new Vector2Int[]{Vector2Int.right, Vector2Int.up, Vector2Int.one}), // 2x2
                ("+mob", RoomType.Mob, new Vector2Int[] { Vector2Int.left, Vector2Int.right, Vector2Int.up, Vector2Int.down }) // +
            };
            Dungeon d = new Dungeon(options, 204, new(){ { RoomType.Mob, 50000 }}, isLayered: true);
            d.Print();
            SpawnedObjects = d.Visualize();
        }
    }
